/**
 * Copy template files from packages/templates
 */
export async function copyTemplateFiles(
  targetDir: string,
  templateName: string = 'suro-buya'
): Promise<void> {
  const templateSrc = path.join(TEMPLATE_SOURCE, 'src');
  const templateDest = path.join(targetDir, 'templates');
  
  if (await fs.pathExists(templateSrc)) {
    await fs.copy(templateSrc, templateDest, { overwrite: true });
  }
}

/**
 * Get list of available templates
 */
export async function getAvailableTemplates(): Promise<string[]> {
  const templatesDir = path.join(TEMPLATE_SOURCE, '..');
  if (!(await fs.pathExists(templatesDir))) {
    return ['suro-buya'];
  }
  
  const entries = await fs.readdir(templatesDir, { withFileTypes: true });
  return entries
    .filter(d => d.isDirectory())
    .map(d => d.name);
}