/**
 * @suro-buya/cli - Scaffold Utilities
 * 
 * Utility functions for scaffolding universe templates.
 */

import fs from 'fs-extra';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

/**
 * Template source directory
 */
const TEMPLATE_SOURCE = path.resolve(__dirname, '../../../templates/universe');

/**
 * Bible directory structure
 */
export const BIBLE_DIRECTORIES = [
  '01-character-bible',
  '02-world-bible',
  '03-story-bible',
  '04-visual-bible',
  '05-production-bible',
];

/**
 * Scaffold a new universe from template
 */
export async function scaffoldUniverse(
  targetDir: string,
  universeId: string,
  universeName: string,
  template: string = 'suro-buya'
): Promise<void> {
  const templatePath = path.join(TEMPLATE_SOURCE, 'src');
  const biblePath = path.join(targetDir, 'bible');
  
  // Create bible directories
  for (const dir of BIBLE_DIRECTORIES) {
    await fs.ensureDir(path.join(biblePath, dir));
  }
  
  // Copy template files if they exist
  if (await fs.pathExists(templatePath)) {
    await fs.copy(templatePath, path.join(targetDir, 'templates'), {
      overwrite: true,
    });
  }
  
  // Create universe.yaml template
  await createUniverseYaml(targetDir, universeId, universeName);
  
  // Create placeholder bible files
  await createPlaceholderBibleFiles(biblePath, universeId, universeName);
  
  // Create .gitignore
  await createGitignore(targetDir);
}

